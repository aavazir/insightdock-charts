#include "insightdock/charts.h"
#include "insightdock/pdf/podofo.h"

#include <podofo/podofo.h>
#include <iostream>

int main() {
  using namespace PoDoFo;

  PdfMemDocument doc;
  PdfPainter painter;
  auto& page = doc.GetPages().CreatePage(PdfPageSize::A4);
  painter.SetCanvas(page);

  insightdock::charts::ExportOptions raster_opts;
  raster_opts.supersample = 2;

  insightdock::charts::ExportOptions vector_opts;
  vector_opts.pdf_backend = insightdock::charts::PdfBackend::Vector;

  insightdock::charts::BarChart bar;
  bar.options().width = 480;
  bar.options().height = 280;
  bar.options().title = "Sales";
  bar.set_categories({"A", "B", "C"});
  bar.add_series("2024", {30, 45, 60});
  bar.add_series("2025", {40, 50, 55});
  insightdock::charts::ChartExporter::draw_pdf(doc, painter, bar, 72, 500, 220, 130, vector_opts);

  insightdock::charts::LineChart line;
  line.options().width = 480;
  line.options().height = 280;
  line.set_categories({"W1", "W2", "W3", "W4"});
  line.add_series("Trend", {5, 12, 8, 15});
  insightdock::charts::ChartExporter::draw_pdf(doc, painter, line, 320, 500, 220, 130, vector_opts);

  insightdock::charts::PieChart pie;
  pie.options().width = 280;
  pie.options().height = 280;
  pie.options().background = insightdock::charts::Color::white();
  pie.add_slice("A", 50);
  pie.add_slice("B", 30);
  pie.add_slice("C", 20);
  insightdock::charts::ChartExporter::draw_pdf(doc, painter, pie, 72, 200, 130, 130, vector_opts);

  painter.FinishDrawing();
  doc.Save("chart_report.pdf");
  std::cout << "Wrote chart_report.pdf (vector PDF)\n";

  if (insightdock::charts::ChartExporter::save(pie, "pie_vector.pdf", vector_opts))
    std::cout << "Wrote pie_vector.pdf (standalone vector pie via ChartExporter::save)\n";

  // --- PdfReportBuilder-driven multi-page report ---
  {
    using namespace insightdock::charts;

    PdfMemDocument report_doc;
    PdfPainter report_painter;
    auto &page1 = report_doc.GetPages().CreatePage(PdfPageSize::A4);
    report_painter.SetCanvas(page1);

    PdfFont &font = report_doc.GetFonts().GetStandard14Font(PdfStandard14FontType::Helvetica);
    PdfFont &font_bold =
        report_doc.GetFonts().GetStandard14Font(PdfStandard14FontType::HelveticaBold);
    report_painter.TextState.SetFont(font, 10);

    pdf::PdfReportBuilder builder(report_doc, report_painter, font, font_bold);
    builder.draw_header_bar("Quarterly Chart Report");

    builder.section_title("Revenue Overview");

    ExportOptions raster_opts2;
    raster_opts2.supersample = 2;
    ExportOptions vector_opts2;
    vector_opts2.pdf_backend = PdfBackend::Vector;

    BarChart bar2;
    bar2.options().width = 480;
    bar2.options().height = 280;
    bar2.options().title = "Quarterly Sales";
    bar2.set_categories({"Q1", "Q2", "Q3", "Q4"});
    bar2.add_series("2024", {30, 45, 60, 50});
    bar2.add_series("2025", {40, 50, 55, 65});
    builder.draw_chart_flow(pdf::PdfPageLayout::margin_l_mm, builder.content_width_mm(), 90, bar2,
                            "Quarterly Sales by Year", raster_opts2);

    LineChart line2;
    line2.options().width = 480;
    line2.options().height = 280;
    line2.set_categories({"W1", "W2", "W3", "W4"});
    line2.add_series("Trend", {5, 12, 8, 15});
    builder.draw_chart_flow(pdf::PdfPageLayout::margin_l_mm, builder.content_width_mm(), 90, line2,
                            "Weekly Trend", raster_opts2);

    builder.section_title("Distribution");

    PieChart pie2;
    pie2.options().width = 280;
    pie2.options().height = 280;
    pie2.options().background = Color::white();
    pie2.add_slice("A", 50);
    pie2.add_slice("B", 30);
    pie2.add_slice("C", 20);
    builder.draw_chart_flow(pdf::PdfPageLayout::margin_l_mm, 90, 90, pie2, "Category Split",
                            vector_opts2);

    PieChart pie3;
    pie3.options().width = 280;
    pie3.options().height = 280;
    pie3.options().background = Color::white();
    pie3.add_slice("X", 70);
    pie3.add_slice("Y", 30);
    builder.draw_chart_flow(pdf::PdfPageLayout::margin_l_mm, 90, 90, pie3, "Region Split",
                            vector_opts2);

    builder.draw_footers("demo-user", "Generated by podofo_report_example");
    report_doc.Save("report_builder_example.pdf");
    std::cout << "Wrote report_builder_example.pdf (multi-page PdfReportBuilder demo)\n";
  }

  return 0;
}
